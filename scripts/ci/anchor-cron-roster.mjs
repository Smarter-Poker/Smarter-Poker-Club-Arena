#!/usr/bin/env node
/**
 * ANCHOR THE SCHEDULED-WORK ROSTER OUTSIDE THE DATABASE.
 *
 * 20260906114257_the_cron_roster_goes_too removed `ca_expected_cron_jobs` and
 * the hourly job that watched it, correctly: it was a monitoring cron, and the
 * owner had just said we do not add those.
 *
 * What it could not remove is the finding it was built on, which that migration
 * keeps in prose: migration 20260831112020 is recorded APPLIED and the cron job
 * it created was simply not in `cron.job` any more. Nothing in the estate can
 * see that happen, because every cron check measures jobs that RUN AND FAIL,
 * and a job that no longer exists never fails.
 *
 * This is that reader, without the watcher. No table, no schedule of its own:
 * it rides Cron Health's existing timer, writes a file git owns, and the count
 * in that file is pinned by a law test that needs no database. A job that
 * appears or vanishes moves the number, and the number cannot move without a
 * reviewed edit in two places.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname } from 'node:path';
import { supabaseServerHeaders } from './supabase-auth-headers.mjs';

const FILE = 'docs/attestation/cron-roster.tsv';
/** 20260910073355 restored two bust-sweep rows disabled; that is source, not measurement. */
const RETAINED_INACTIVE = 2;

const url = process.env.SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !key) {
  console.error('[cron-roster] SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY must be set.');
  process.exit(2);
}

const res = await fetch(`${url}/rest/v1/rpc/fn_ca_cron_health`, {
  method: 'POST',
  headers: supabaseServerHeaders(key, { 'Content-Type': 'application/json' }),
  body: JSON.stringify({ p_window: '24 hours' }),
});

// Never coerce an unreadable answer into an empty one.
if (!res.ok) {
  console.error(
    `[cron-roster] fn_ca_cron_health returned HTTP ${res.status} - refusing to treat that as "no jobs".`
  );
  process.exit(2);
}
const jobs = await res.json();
if (!Array.isArray(jobs) || jobs.length === 0) {
  console.error(
    '[cron-roster] the database reported no active scheduled jobs at all. That is not a normal empty; refusing.'
  );
  process.exit(2);
}

const rows = jobs.map((j) => `${String(j.jobname)}\t${String(j.schedule)}`).sort();
const observed = new Date().toISOString().replace(/\.\d{3}Z$/, 'Z');
const header = [
  '# Every ACTIVE pg_cron job on production, from fn_ca_cron_health().',
  "# Regenerated by scripts/ci/anchor-cron-roster.mjs on Cron Health's existing schedule.",
  '# A change here is a change to what this platform runs on a timer. Never edit a',
  '# line to make a check pass: tests/the-scheduled-work-roster-is-pinned.law.test.ts',
  '# pins the count, and the count is supposed to be argued about.',
  `# observed_at: ${observed}`,
  `# active: ${rows.length}`,
  `# retained-inactive: ${RETAINED_INACTIVE}\tthe two bust sweeps, restored disabled by 20260910073355`,
  '# jobname\tschedule',
].join('\n');

const previous = existsSync(FILE) ? readFileSync(FILE, 'utf8') : '';
const was = Number(/^#\s*active:\s*(\d+)/m.exec(previous)?.[1]);

mkdirSync(dirname(FILE), { recursive: true });
writeFileSync(FILE, `${header}\n${rows.join('\n')}\n`);

if (!Number.isFinite(was)) {
  console.log(`[cron-roster] seeded ${rows.length} active job(s).`);
  process.exit(0);
}
if (was === rows.length) {
  console.log(`[cron-roster] ${rows.length} active job(s), unchanged.`);
  process.exit(0);
}

console.error('');
console.error(`[cron-roster] THE NUMBER OF ACTIVE SCHEDULED JOBS CHANGED: ${was} -> ${rows.length}.`);
console.error('');
console.error('  A job appeared or vanished on production. Neither is routine. A new one');
console.error('  is periodic work nobody reviewed; a missing one is 20260831112020');
console.error('  happening again - a migration recorded as applied whose cron job is not');
console.error('  in cron.job any more, which nothing else in this estate can see, because');
console.error('  every other cron check measures jobs that RUN AND FAIL and a job that no');
console.error('  longer exists never fails.');
console.error('');
console.error('  Commit the regenerated file AND the new count in');
console.error('  tests/the-scheduled-work-roster-is-pinned.law.test.ts, in one reviewed');
console.error('  change that says which job moved and why.');
console.error('');
process.exit(1);
