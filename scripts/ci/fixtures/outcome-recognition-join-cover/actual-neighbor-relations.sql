recognized_at timestamp with time zone,
game_union_id text,
shaped boolean NOT NULL,
accepted_rake text,
participants jsonb,
CONSTRAINT union_pnl_cash_outcome_touches_pkey PRIMARY KEY (table_id, hand_number));
