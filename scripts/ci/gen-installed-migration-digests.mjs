#!/usr/bin/env node
/**
 * ═══════════════════════════════════════════════════════════════════════════
 *  GENERATE: what production applied, and the digest a record file must match
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Writes scripts/ci/installed-migration-digests.d/<YYYYMM>.txt, one
 * `<version> <sha256>` per line, for every applied migration that has
 * recordable statements and NO file in either estate repo.
 *
 * That set is exactly the set of versions a record file can legitimately be
 * written for, so the manifest shrinks as the parity gap closes - the healthy
 * direction, and a number somebody can watch.
 *
 * WHY SHARDED BY MONTH. CLAUDE.md 10.9 rule 9 and the schema-manifest.d
 * README: a single generated file that every branch regenerates is a merge
 * conflict in every pull request. Two months written independently cannot
 * conflict.
 *
 * WHY sha256 OF THE JOINED STATEMENTS. Supabase splits a migration file INTO
 * `statements`, so joining them with newlines is the faithful round trip;
 * trailing newlines are stripped on both sides so a file ending in one newline
 * and the same file ending in three both match. This is the same arithmetic
 * the checks do in scripts/ci/recorded-migration.mjs - deliberately one
 * definition, in one place.
 *
 * READ-ONLY against the database, like backfill-unrecorded-migrations.mjs. It
 * SELECTs and writes local files; it never applies or alters anything, and it
 * runs no DDL, so the break window (Production DDL policy rule 8) does not
 * apply to it.
 *
 * NOBODY HAND-WRITES A SHARD. The checks read these from `origin/main`
 * precisely so that a pull request cannot add its own pardon, and that
 * property only holds while the trusted default-branch workflow is the sole
 * writer. tests/a-migration-file-that-records-is-not-a-proposal.law.test.ts
 * pins the format so a hand-edit is visible.
 *
 * Usage (in the workflow that holds the service role):
 *   SUPABASE_URL=... SUPABASE_SERVICE_ROLE_KEY=... \
 *     node scripts/ci/gen-installed-migration-digests.mjs [--check]
 *
 * --check writes nothing and exits 1 if the shards on disk disagree with
 * production, which is how the scheduled job reports drift.
 *
 * Exit: 0 written/agreed · 1 --check found drift · 2 could not ask
 */
import { readdirSync, writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { supabaseServerHeaders } from './supabase-auth-headers.mjs';
import { DIGEST_DIR } from './recorded-migration.mjs';

const CHECK = process.argv.includes('--check');
const ROOT = process.cwd();
const OUT = resolve(ROOT, DIGEST_DIR);
const SB_URL = process.env.SUPABASE_URL || '';
const SB_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY || '';

if (!SB_URL || !SB_KEY) {
  console.error('[installed-digests] COULD NOT ASK: no SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY.');
  console.error('   This is not "no drift". Exit 2.');
  process.exit(2);
}

/** Every 14-digit version either estate repo has a file for. */
function versionsWithAFile() {
  const have = new Set();
  for (const dir of [
    resolve(ROOT, 'supabase/migrations'),
    resolve(ROOT, '..', 'Smarter-Poker-World-Hub/supabase/migrations'),
    process.env.SIBLING_MIGRATIONS_DIR || '',
  ]) {
    if (!dir || !existsSync(dir)) continue;
    for (const f of readdirSync(dir)) {
      const m = /^(\d{14})(?:[_.]|$)/.exec(f);
      if (m) have.add(m[1]);
    }
  }
  return have;
}

async function fetchApplied() {
  const res = await fetch(`${SB_URL}/rest/v1/rpc/zz_backfill_migrations`, {
    method: 'POST',
    headers: supabaseServerHeaders(SB_KEY, { 'content-type': 'application/json' }),
    body: JSON.stringify({ p_since: '00000000000000' }),
  });
  if (!res.ok) throw new Error(`REST ${res.status}: ${(await res.text()).slice(0, 300)}`);
  return res.json();
}

let rows;
try {
  rows = await fetchApplied();
} catch (err) {
  console.error(`[installed-digests] COULD NOT ASK: ${err?.message || err}`);
  process.exit(2);
}

const have = versionsWithAFile();
const shards = new Map();
let considered = 0;
for (const r of rows) {
  if (!/^\d{14}$/.test(r.version || '')) continue;
  const stmts = Array.isArray(r.statements) ? r.statements : [];
  if (stmts.length === 0) continue; // unrecoverable; nothing to record
  considered += 1;
  if (have.has(r.version)) continue; // already written down
  const body = stmts.join('\n').replace(/\n+$/, '');
  const sha = createHash('sha256').update(body, 'utf8').digest('hex');
  const ym = r.version.slice(0, 6);
  if (!shards.has(ym)) shards.set(ym, []);
  shards.get(ym).push(`${r.version} ${sha}`);
}

const header =
  '# GENERATED by scripts/ci/gen-installed-migration-digests.mjs from\n' +
  '# supabase_migrations.schema_migrations. Do not hand-edit: the checks read\n' +
  '# this from origin/main precisely so a pull request cannot add its own\n' +
  '# pardon, and that only holds while the trusted workflow is the sole writer.\n' +
  '# <14-digit version> <sha256 of the applied statements, joined by \\n, rtrimmed>\n';

const want = new Map();
for (const [ym, lines] of shards) want.set(`${ym}.txt`, header + lines.sort().join('\n') + '\n');

if (CHECK) {
  const onDisk = new Map();
  if (existsSync(OUT)) {
    for (const f of readdirSync(OUT)) {
      if (f.endsWith('.txt')) onDisk.set(f, readFileSync(join(OUT, f), 'utf8'));
    }
  }
  const differing = [];
  for (const [f, body] of want) if (onDisk.get(f) !== body) differing.push(f);
  for (const f of onDisk.keys()) if (!want.has(f)) differing.push(`${f} (no longer produced)`);
  if (differing.length) {
    console.error(
      `[installed-digests] DRIFT in ${differing.length} shard(s): ${differing.join(', ')}`
    );
    console.error('   Regenerate and commit: node scripts/ci/gen-installed-migration-digests.mjs');
    process.exit(1);
  }
  console.log(`[installed-digests] OK - ${want.size} shard(s) agree with production.`);
  process.exit(0);
}

mkdirSync(OUT, { recursive: true });
for (const [f, body] of want) writeFileSync(join(OUT, f), body);
const total = [...shards.values()].reduce((n, l) => n + l.length, 0);
console.log(
  `[installed-digests] ${considered} applied migration(s) with recordable statements; ` +
    `${total} still have no file in either repo, written to ${want.size} shard(s).`
);
