#!/usr/bin/env python3
"""Measure visible crown headroom from shipped library art; never alter the art."""
from pathlib import Path
import sys
from PIL import Image

assets = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / 'Documents/Smarter-Poker-World-Hub/public/avatars/table'
output = Path(__file__).resolve().parent.parent / 'src/components/table/avatarCrownBounds.ts'
rows = []
for path in sorted(assets.glob('*.webp')):
    if not path.name.startswith(('free_', 'vip_')):
        continue
    with Image.open(path) as image:
        # Ignore barely visible feathering; this is the visible head, not its glow.
        alpha = image.convert('RGBA').getchannel('A').point(lambda a: 255 if a >= 16 else 0)
        bounds = alpha.getbbox()
        if not bounds:
            raise ValueError(f'Avatar has no visible subject: {path.name}')
        rows.append(f"  '{path.name}': {bounds[1] / image.height:.6f},")
if not rows:
    raise ValueError('No shipped library avatar art found')
output.write_text('''/** Generated by scripts/measure-avatar-crowns.py from the shipped art.
 * Fraction of the image canvas above its visible crown (alpha >= 16).
 * Library canvases fit their height into the square avatar slot; transparency
 * is not a head. Keeping this separate from bust gain preserves avatar size.
 */
export const AVATAR_CROWN_TOP: Readonly<Record<string, number>> = {
''' + '\n'.join(rows) + '''
};

/** Unknown/uploaded avatars keep their existing image-box boundary. */
export function avatarCrownTop(source: string | null | undefined): number {
  const file = source && /\\/avatars\\/table\\/((?:free|vip)_[\\w-]+(?:@2x)?\\.webp)(?:[?#]|$)/.exec(source)?.[1];
  return (file && AVATAR_CROWN_TOP[file]) || 0;
}

/** Project the measured visible crown through the image's rendered scale. */
export function paintedAvatarTop(image: HTMLImageElement): number {
  const box = image.getBoundingClientRect();
  return box.top + box.height * avatarCrownTop(image.currentSrc || image.src);
}
''', encoding='utf-8')
print(f'Measured {len(rows)} avatar crowns; wrote {output}')
