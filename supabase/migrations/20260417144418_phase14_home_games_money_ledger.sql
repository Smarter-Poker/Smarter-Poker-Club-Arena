-- ══════════════════════════════════════════════════════════════════════
--  PHASE 14: HOME-GAMES MONEY LEDGER
-- ══════════════════════════════════════════════════════════════════════
--
--  "All-in-one home game": the host never leaves the platform to run the
--  night. Phase 14 adds the money-tracking foundation — buyins, rebuys,
--  addons, cashouts, computed settlements, and per-group payment links.
--
--  DESIGN NOTES
--
--  • Amounts stored in INTEGER CENTS, not numeric dollars. Avoids
--    floating-point drift during settlement math. $50.00 → 5000.
--
--  • Chip counts optional (INTEGER). Cash games often skip them; some
--    tournaments track them. When present, the client can show chip-level
--    detail; when absent, only dollars roll up.
--
--  • `commander_home_buyins.kind` is a text column with a CHECK constraint:
--      buyin    — initial buy-in
--      rebuy    — re-buy after busting (tournaments) or reloading (cash)
--      addon    — add-on at break (tournaments)
--      adjustment — manual correction (host typo, chop, etc.)
--
--  • `commander_home_cashouts` is separate from buyins rather than a
--    "cashout" kind on buyins, because it has different semantics:
--    a player can have many buyins but only one cashout per game.
--
--  • `commander_home_settlements` is computed output, not input. Host
--    calls fn_home_compute_settlements(game_id) which replaces all
--    rows for that game with a minimum-transaction settlement plan.
--    Each row then gets marked paid/disputed individually as payment
--    happens IRL.
--
--  • `commander_home_group_payment_links` per group, not per user —
--    it's the HOST's payment handles, so players know where to send.
--    (Per-user payment preferences would be per-user on a profile, not
--    in this table.)
--
--  AUTHORIZATION MODEL (enforced in RPCs, not via RLS)
--
--  • Staff (owner/admin of the group) can write all ledger rows for
--    any game in their group.
--  • Players can read their own ledger rows for games they attended
--    (RSVP is_confirmed=true).
--  • Settlement rows can be marked paid by EITHER the payer or payee
--    — whoever acknowledges first.
-- ══════════════════════════════════════════════════════════════════════

-- ── commander_home_buyins ────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS commander_home_buyins (
    id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    game_id      uuid NOT NULL REFERENCES commander_home_games(id) ON DELETE CASCADE,
    user_id      uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    kind         text NOT NULL CHECK (kind IN ('buyin','rebuy','addon','adjustment')),
    amount_cents integer NOT NULL,
    chip_count   integer,
    note         text,
    recorded_by  uuid NOT NULL REFERENCES auth.users(id),
    recorded_at  timestamptz NOT NULL DEFAULT NOW(),
    created_at   timestamptz NOT NULL DEFAULT NOW(),
    updated_at   timestamptz NOT NULL DEFAULT NOW(),
    CONSTRAINT commander_home_buyins_amount_nonneg
        CHECK (kind = 'adjustment' OR amount_cents >= 0)
);

CREATE INDEX IF NOT EXISTS idx_commander_home_buyins_game
    ON commander_home_buyins (game_id);
CREATE INDEX IF NOT EXISTS idx_commander_home_buyins_user
    ON commander_home_buyins (user_id);
CREATE INDEX IF NOT EXISTS idx_commander_home_buyins_game_user
    ON commander_home_buyins (game_id, user_id);

-- ── commander_home_cashouts ──────────────────────────────────────────
-- One row per player per game. Unique(game_id, user_id).
CREATE TABLE IF NOT EXISTS commander_home_cashouts (
    id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    game_id      uuid NOT NULL REFERENCES commander_home_games(id) ON DELETE CASCADE,
    user_id      uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    amount_cents integer NOT NULL CHECK (amount_cents >= 0),
    chip_count   integer,
    note         text,
    recorded_by  uuid NOT NULL REFERENCES auth.users(id),
    recorded_at  timestamptz NOT NULL DEFAULT NOW(),
    created_at   timestamptz NOT NULL DEFAULT NOW(),
    updated_at   timestamptz NOT NULL DEFAULT NOW(),
    UNIQUE (game_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_commander_home_cashouts_user
    ON commander_home_cashouts (user_id);

-- ── commander_home_settlements ───────────────────────────────────────
-- Computed rows: who pays whom, how much. Regenerated by the RPC.
CREATE TABLE IF NOT EXISTS commander_home_settlements (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    game_id         uuid NOT NULL REFERENCES commander_home_games(id) ON DELETE CASCADE,
    payer_user_id   uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    payee_user_id   uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    amount_cents    integer NOT NULL CHECK (amount_cents > 0),
    status          text NOT NULL DEFAULT 'pending'
                      CHECK (status IN ('pending','paid','disputed','waived')),
    paid_at         timestamptz,
    paid_via        text,        -- 'venmo' | 'zelle' | 'paypal' | 'cashapp' | 'cash' | 'other'
    paid_note       text,
    computed_at     timestamptz NOT NULL DEFAULT NOW(),
    updated_at      timestamptz NOT NULL DEFAULT NOW(),
    CONSTRAINT commander_home_settlements_no_self_pay
        CHECK (payer_user_id <> payee_user_id)
);

CREATE INDEX IF NOT EXISTS idx_commander_home_settlements_game
    ON commander_home_settlements (game_id);
CREATE INDEX IF NOT EXISTS idx_commander_home_settlements_payer
    ON commander_home_settlements (payer_user_id, status);
CREATE INDEX IF NOT EXISTS idx_commander_home_settlements_payee
    ON commander_home_settlements (payee_user_id, status);

-- ── commander_home_group_payment_links ───────────────────────────────
-- Host's payment handles. Players tap to send via the linked app.
CREATE TABLE IF NOT EXISTS commander_home_group_payment_links (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    group_id    uuid NOT NULL REFERENCES commander_home_groups(id) ON DELETE CASCADE,
    kind        text NOT NULL
                  CHECK (kind IN ('venmo','zelle','paypal','cashapp','revolut','other')),
    handle      text NOT NULL,  -- '@danbekavac', 'dan@example.com', etc.
    label       text,           -- optional human label
    sort_order  integer NOT NULL DEFAULT 0,
    is_active   boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT NOW(),
    updated_at  timestamptz NOT NULL DEFAULT NOW(),
    UNIQUE (group_id, kind, handle)
);

CREATE INDEX IF NOT EXISTS idx_commander_home_group_payment_links_group
    ON commander_home_group_payment_links (group_id, is_active);

