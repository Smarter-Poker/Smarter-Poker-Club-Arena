-- Diamond Accounting Standard, Lane E: every earn engine has a budget line,
-- a per-user per-day cap ledger, catalogs keep history, and the trivia
-- tournament cut is banked instead of burned by omission.
--
-- Standard references: DR7 (every earn engine has a budget line and a per-user
-- per-day cap in the database), DR14 (nothing is burned by omission), D21
-- (earn engines are budgets, not faucets; the catalog that prices awards is
-- versioned and every edit logged).
--
-- LOG-ONLY. Nothing here refuses a movement. The budget ledger and the cap
-- ledger record what happened and file an incident when a line is crossed;
-- the trigger is wrapped so it can never abort an insert into the journal.
--
-- BUDGET AND CAP NUMBERS ARE PROPOSED PLACEHOLDERS, NOT DAN'S NUMBERS.
-- 2,500,000 per engine per month is the constant already inside
-- award_diamonds_v2 (c_platform_budget), reused here so that no engine starts
-- life at zero and files a false incident on its first award. The daily caps
-- are what the code enforces today where it enforces anything at all
-- (catalog_v2 110 = the non-VIP daily cap in award_diamonds_v2; trivia 2,000 =
-- the largest solo award ceiling in trivia_diamond_award_limits). Every other
-- engine is NULL, meaning uncapped today, which is a statement of fact about
-- the code and not a recommendation. Dan sets the real numbers.
--
-- One migration, one transaction, applied once.

BEGIN;

SET LOCAL lock_timeout = '4s';

