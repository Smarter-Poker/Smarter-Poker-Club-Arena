BEGIN
    IF (SELECT md5(p.prosrc)
          FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
         WHERE n.nspname = 'public' AND p.proname = 'enter_trivia_tournament_v2')
       IS DISTINCT FROM 'ae3917ca8ce919a41f448f224ac53dab' THEN
        RAISE EXCEPTION 'Lane E: enter_trivia_tournament_v2 body changed since this migration was written (expected md5 ae3917ca8ce919a41f448f224ac53dab)';
    END IF;
