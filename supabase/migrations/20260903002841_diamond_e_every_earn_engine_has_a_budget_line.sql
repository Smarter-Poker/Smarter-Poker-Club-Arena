-- ---------------------------------------------------------------------------
-- 9. award_diamonds_v2: the lost-update fix, plus the issuance class.
--
--    The profile row is read without a lock and written back as an absolute
--    value, so a concurrent writer between the read and the write is silently
--    overwritten (lane 3 section 5.2). Two edits, each asserted to match
--    exactly once against the LIVE body, and the whole 25,090 character
--    function is otherwise carried through unchanged: the patch is applied to
--    pg_get_functiondef() AT APPLY TIME rather than to a hand copied body, so
--    no other character can move, and the md5 guard aborts if the live body is
--    not the one this migration was written against.
--
--      edit 1: the profile SELECT takes FOR UPDATE.
--      edit 2: the journal INSERT names its counterparty and issuance class.
--
--    Lock order is unchanged in substance: this function already serialises
--    platform wide on the diamond_platform_budget period row, and that lock is
--    taken AFTER the profile read, so profile then budget remains the only
--    ordering and no new deadlock edge is introduced.
-- ---------------------------------------------------------------------------

DO $patch$
DECLARE
    v_oid      oid;
    v_old_def  text;
    v_new_def  text;
    v_old_a    text := E'      FROM public.profiles\n     WHERE id = p_user_id;';
    v_new_a    text := E'      FROM public.profiles\n     WHERE id = p_user_id\n       FOR UPDATE;';
    v_old_b    text;
    v_new_b    text;
    v_expected integer;
BEGIN
    v_old_b :=
        E'    INSERT INTO public.diamond_transactions (\n'
     || E'        user_id, amount, transaction_type, type, description,\n'
     || E'        balance_after, reference_id, metadata, created_at\n'
     || E'    ) VALUES (\n'
     || E'        p_user_id,\n'
     || E'        v_award,\n'
     || E'        p_action_key,\n'
     || E'        p_action_key,\n'
     || E'        format(''Diamond Rewards v2: %s%s'', p_action_key,\n'
     || E'               CASE WHEN v_capped THEN '' (capped)'' ELSE '''' END),\n'
     || E'        v_new_balance,\n'
     || E'        CASE WHEN v_reference_id = '''' THEN NULL ELSE v_reference_id END,\n'
     || E'        v_metadata,\n'
     || E'        v_now\n'
     || E'    );';

    v_new_b :=
        E'    INSERT INTO public.diamond_transactions (\n'
     || E'        user_id, amount, transaction_type, type, description,\n'
     || E'        balance_after, reference_id, metadata, created_at,\n'
     || E'        counterparty, issuance_class\n'
     || E'    ) VALUES (\n'
     || E'        p_user_id,\n'
     || E'        v_award,\n'
     || E'        p_action_key,\n'
     || E'        p_action_key,\n'
     || E'        format(''Diamond Rewards v2: %s%s'', p_action_key,\n'
     || E'               CASE WHEN v_capped THEN '' (capped)'' ELSE '''' END),\n'
     || E'        v_new_balance,\n'
     || E'        CASE WHEN v_reference_id = '''' THEN NULL ELSE v_reference_id END,\n'
     || E'        v_metadata,\n'
     || E'        v_now,\n'
     || E'        ''promo_budget:catalog_v2'',\n'
     || E'        ''promotional''\n'
     || E'    );';

    SELECT p.oid INTO v_oid
      FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
     WHERE n.nspname = 'public'
       AND p.proname = 'award_diamonds_v2'
       AND pg_get_function_identity_arguments(p.oid)
           = 'p_user_id uuid, p_action_key text, p_reference_id text, p_target_id text, p_metadata jsonb';

    IF v_oid IS NULL THEN
        RAISE EXCEPTION 'Lane E: award_diamonds_v2(uuid,text,text,text,jsonb) not found';
    END IF;

    IF (SELECT md5(prosrc) FROM pg_proc WHERE oid = v_oid) <> '902c18015fd648bc50ca75525340c8e7' THEN
        RAISE EXCEPTION 'Lane E: award_diamonds_v2 body changed since this migration was written (expected md5 902c18015fd648bc50ca75525340c8e7). Re-read the live body before patching.';
    END IF;

    v_old_def := pg_get_functiondef(v_oid);

    -- Each target must occur exactly once, or the patch is not surgical.
    IF (length(v_old_def) - length(replace(v_old_def, v_old_a, ''))) / length(v_old_a) <> 1 THEN
        RAISE EXCEPTION 'Lane E: the profile read fragment does not occur exactly once in award_diamonds_v2';
    END IF;
    IF (length(v_old_def) - length(replace(v_old_def, v_old_b, ''))) / length(v_old_b) <> 1 THEN
        RAISE EXCEPTION 'Lane E: the journal insert fragment does not occur exactly once in award_diamonds_v2';
    END IF;

    v_new_def := replace(replace(v_old_def, v_old_a, v_new_a), v_old_b, v_new_b);

    -- The only characters that may differ are the ones the two edits add.
    v_expected := length(v_old_def)
                + (length(v_new_a) - length(v_old_a))
                + (length(v_new_b) - length(v_old_b));
    IF length(v_new_def) <> v_expected THEN
        RAISE EXCEPTION 'Lane E: the award_diamonds_v2 patch moved % characters, expected %',
            length(v_new_def) - length(v_old_def), v_expected - length(v_old_def);
    END IF;

    EXECUTE v_new_def;
END;
$patch$;

-- ---------------------------------------------------------------------------
-- 10. enter_trivia_tournament_v2: the entry fee cut is banked, not burned.
--
--     v_net := v_fee - floor(v_fee * 0.10) has always kept a slice of every
--     entry fee out of the prize pool and credited it to nothing: three
--     completed events collected 5,200 in fees, pooled 4,984, and 216
--     diamonds left the players and reached no account at all (lane 3, 4.2).
--     The cut now lands in ca_diamond_house with a ledger row (DR14).
--
--     Nothing else changes: the same VIP gate, the same fee, the same net to
--     the pool, the same references, the same return shape. The rate stays
--     floor(10 percent); whether it should be 10 percent rounded is Dan's
--     decision 8 in the standard and is NOT changed here.
--
--     This function is service_role only and has 0 calls in the last 30 days
--     (0 trivia_tourn_entry_% rows exist in the journal all time), so the
--     change cannot disturb live play.
