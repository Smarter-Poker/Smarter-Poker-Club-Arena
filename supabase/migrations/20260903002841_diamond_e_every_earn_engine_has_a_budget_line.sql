-- ---------------------------------------------------------------------------
-- 5. Engine attribution. Pure function from the shape of a journal row to the
--    name of the engine that wrote it. The shapes are the ones lane 3
--    documented in
--    docs/audits/2026-09-02-diamond-economy/lane3-earn-engines-and-transfers.md.
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.fn_ca_diamond_engine_of(
    p_type             text,
    p_transaction_type text,
    p_source           text,
    p_description      text,
    p_reference_id     text
) RETURNS text
LANGUAGE sql
IMMUTABLE
AS $fn$
    SELECT CASE
        -- Reference shapes are the most specific evidence a row carries.
        WHEN starts_with(p_reference_id, 'trivia_tourn_')     THEN 'trivia_tournaments'
        WHEN starts_with(p_reference_id, 'trivia_session_')   THEN 'trivia'
        WHEN starts_with(p_reference_id, 'trivia_wheel_')     THEN 'trivia'
        WHEN starts_with(p_reference_id, 'challenge_claim')   THEN 'daily_challenges'
        WHEN starts_with(p_reference_id, 'streak_milestone_') THEN 'share_streak'
        WHEN starts_with(p_reference_id, 'signup:')           THEN 'signup'
        WHEN starts_with(p_reference_id, 'easter_egg_')       THEN 'catalog_v2'
        WHEN starts_with(p_reference_id, 'video_favorite_')   THEN 'catalog_v2'
        WHEN starts_with(p_reference_id, 'vip_stipend_')      THEN 'catalog_v2'

        -- source is set by exactly three writers and each names its engine.
        WHEN p_source = 'complete_daily_challenge' THEN 'memory_game'
        WHEN p_source = 'handle_new_user'          THEN 'signup'
        WHEN p_source = 'union'                    THEN 'union_grant'

        -- transaction_type where it is set, falling back to type.
        WHEN COALESCE(p_transaction_type, p_type) IN (
                'referral_bonus', 'referral_bonus_reversal', 'referral_qualified',
                'referral_referee', 'referral_vip_conversion')             THEN 'referrals'
        WHEN COALESCE(p_transaction_type, p_type) = 'signup_bonus'         THEN 'signup'
        WHEN COALESCE(p_transaction_type, p_type) = 'union_grant'          THEN 'union_grant'
        WHEN COALESCE(p_transaction_type, p_type) IN (
                'pvp_refund', 'pvp_win', 'pvp_tie_refund', 'trivia_run',
                'trivia_daily_bonus', 'daily_trivia', 'trivia_reward',
                'trivia_prize_wheel', 'endless_reward', 'survival_reward',
                'mixed_reward', 'time_attack_reward', 'trivia_double_win')  THEN 'trivia'
        WHEN COALESCE(p_transaction_type, p_type) IN (
                'tournament_prize', 'tournament_entry_refund',
                'tournament_cancel_refund')                                THEN 'trivia_tournaments'
        WHEN COALESCE(p_transaction_type, p_type) = 'daily_challenge_claim' THEN 'daily_challenges'
        WHEN COALESCE(p_transaction_type, p_type) = 'streak_reward'        THEN 'share_streak'
        WHEN COALESCE(p_transaction_type, p_type) IN (
                'daily_login', 'easter_egg', 'training_reward',
                'video_favorite', 'vip_stipend')                           THEN 'catalog_v2'
        WHEN COALESCE(p_transaction_type, p_type) IN (
                'credit', 'earn', 'bonus')                                 THEN 'legacy_credit'

        -- award_diamonds_v2 stamps this description on every row it writes.
        WHEN p_description LIKE 'Diamond Rewards v2:%'                      THEN 'catalog_v2'

        ELSE 'other'
    END;
$fn$;

COMMENT ON FUNCTION public.fn_ca_diamond_engine_of(text, text, text, text, text) IS
  'DR7. Maps one diamond_transactions row to the earn engine that wrote it, from the reference shape, then the source, then the type, then the description. Unknown maps to other. Pure; safe to run over history.';

REVOKE ALL ON FUNCTION public.fn_ca_diamond_engine_of(text, text, text, text, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fn_ca_diamond_engine_of(text, text, text, text, text) TO service_role, authenticated;

-- ---------------------------------------------------------------------------
-- 6. The budget and cap ledger (DR7), LOG-ONLY.
--
--    It never refuses. Everything it does is wrapped in a handler that turns
--    any failure into an incident, because a bookkeeping table must never be
--    able to stop a player being paid.
--
--    Rows that are not promotional issuance are skipped: a purchase, a
--    transfer between two players, a refund, an admin adjustment and an arena
--    movement are all transfers between accounts rather than new issuance, so
--    charging them to an earn budget would be double counting.
--
--    Signup grants arrive with issuance_class 'seeded' or 'promotional'
--    (Lane B, the Mint) and are counted against the 'signup' engine.
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.fn_ca_diamond_earn_ledger()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $fn$
DECLARE
    v_engine  text;
    v_period  text;
    v_day     date;
    v_budget  bigint;
    v_spent   bigint;
    v_awarded bigint;
    v_cap     integer;
    v_at      timestamptz;
BEGIN
    BEGIN
        -- Not promotional issuance: skip.
        IF COALESCE(NEW.issuance_class, '') IN ('purchased', 'transferred', 'refund', 'admin', 'arena') THEN
            RETURN NULL;
        END IF;
        IF COALESCE(NEW.type, '') = 'purchase' OR COALESCE(NEW.transaction_type, '') = 'purchase' THEN
            RETURN NULL;
        END IF;

        v_at     := COALESCE(NEW.created_at, now());
        v_engine := public.fn_ca_diamond_engine_of(
                        NEW.type, NEW.transaction_type, NEW.source,
                        NEW.description, NEW.reference_id);
        v_period := to_char((v_at AT TIME ZONE 'America/Chicago'), 'YYYY-MM');
        v_day    := (v_at AT TIME ZONE 'America/Chicago')::date;

        -- (a) the engine's budget line for the period. A period that does not
        --     exist yet inherits the engine's most recent budget, or the
        --     2,500,000 placeholder if the engine has never had one.
        INSERT INTO public.diamond_reward_budgets (period, engine, budget_diamonds, spent_diamonds, updated_at)
        VALUES (
            v_period,
            v_engine,
            COALESCE(
                (SELECT b.budget_diamonds
                   FROM public.diamond_reward_budgets b
                  WHERE b.engine = v_engine
                    AND b.period < v_period
                  ORDER BY b.period DESC
                  LIMIT 1),
                2500000),
            NEW.amount,
            now())
        ON CONFLICT (period, engine) DO UPDATE
           SET spent_diamonds = diamond_reward_budgets.spent_diamonds + EXCLUDED.spent_diamonds,
               updated_at     = now()
        RETURNING budget_diamonds, spent_diamonds INTO v_budget, v_spent;

        IF v_spent > v_budget THEN
            PERFORM public.fn_ca_diamond_incident(
                'DR7:engine_over_budget', 'warning', NEW.user_id, NEW.amount,
                'fn_ca_diamond_earn_ledger',
                jsonb_build_object(
                    'engine', v_engine, 'period', v_period,
                    'budget_diamonds', v_budget, 'spent_diamonds', v_spent,
                    'journal_id', NEW.id, 'reference_id', NEW.reference_id));
        END IF;

        -- (b) the player's day total for that engine.
        INSERT INTO public.diamond_user_daily_awards (user_id, engine, day, awarded, updated_at)
        VALUES (NEW.user_id, v_engine, v_day, NEW.amount, now())
        ON CONFLICT (user_id, engine, day) DO UPDATE
           SET awarded    = diamond_user_daily_awards.awarded + EXCLUDED.awarded,
               updated_at = now()
        RETURNING awarded INTO v_awarded;

        -- (c) the per-user per-day cap, where one is set.
        SELECT c.max_per_user_per_day
          INTO v_cap
          FROM public.diamond_engine_daily_caps c
         WHERE c.engine = v_engine;

        IF v_cap IS NOT NULL AND v_awarded > v_cap THEN
            PERFORM public.fn_ca_diamond_incident(
                'DR7:user_over_daily_cap', 'warning', NEW.user_id, NEW.amount,
                'fn_ca_diamond_earn_ledger',
                jsonb_build_object(
                    'engine', v_engine, 'day', v_day,
                    'max_per_user_per_day', v_cap, 'awarded_today', v_awarded,
                    'journal_id', NEW.id, 'reference_id', NEW.reference_id));
        END IF;

    EXCEPTION WHEN OTHERS THEN
        -- (e) never raise. A budget line is bookkeeping; the award already
        --     happened and the player keeps it.
        PERFORM public.fn_ca_diamond_incident(
            'DR7:ledger_write_failed', 'warning', NEW.user_id, NEW.amount,
            'fn_ca_diamond_earn_ledger',
            jsonb_build_object(
                'sqlstate', SQLSTATE, 'sqlerrm', SQLERRM,
                'journal_id', NEW.id, 'reference_id', NEW.reference_id));
    END;

    RETURN NULL;
END;
$fn$;

COMMENT ON FUNCTION public.fn_ca_diamond_earn_ledger() IS
  'DR7 LOG-ONLY. AFTER INSERT on diamond_transactions for positive amounts: charges the engine budget line, adds to the per-user per-day total, and files DR7:engine_over_budget / DR7:user_over_daily_cap incidents. Never refuses; any failure becomes DR7:ledger_write_failed.';

REVOKE ALL ON FUNCTION public.fn_ca_diamond_earn_ledger() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS trg_ca_diamond_earn_ledger ON public.diamond_transactions;
CREATE TRIGGER trg_ca_diamond_earn_ledger
    AFTER INSERT ON public.diamond_transactions
    FOR EACH ROW
    WHEN (NEW.amount > 0)
    EXECUTE FUNCTION public.fn_ca_diamond_earn_ledger();

