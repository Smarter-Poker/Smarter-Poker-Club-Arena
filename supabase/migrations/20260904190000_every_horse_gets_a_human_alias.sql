DECLARE
  v_rows int;
  v_dupes int;
  v_clash int;
BEGIN
  SELECT count(*) INTO v_rows FROM zz_horse_alias;
  IF v_rows <> 1000 THEN
    RAISE EXCEPTION 'expected 1000 horses, staged %', v_rows;
  END IF;
  SELECT count(*) - count(DISTINCT lower(alias)) INTO v_dupes FROM zz_horse_alias;
  IF v_dupes <> 0 THEN
    RAISE EXCEPTION '% duplicate aliases in the staged set', v_dupes;
  END IF;
  -- Nobody outside the fleet may already hold one of these names.
  SELECT count(*) INTO v_clash
    FROM public.profiles p
    JOIN zz_horse_alias z ON lower(coalesce(p.alias, '')) = lower(z.alias)
                          OR lower(coalesce(p.username, '')) = lower(z.alias)
   WHERE NOT coalesce(p.is_horse, false);
  IF v_clash <> 0 THEN
    RAISE EXCEPTION '% staged aliases collide with a human alias or username', v_clash;
  END IF;
END $$;

UPDATE public.profiles p
   SET alias = z.alias
  FROM zz_horse_alias z
 WHERE p.id = z.id
   AND coalesce(p.is_horse, false);

DO $$
DECLARE
  v_updated int;
  v_camel int;
  v_distinct int;
BEGIN
  SELECT count(*) INTO v_updated FROM public.profiles p JOIN zz_horse_alias z ON z.id = p.id AND p.alias = z.alias;
  IF v_updated <> 1000 THEN
    RAISE EXCEPTION 'expected 1000 horses renamed, found %', v_updated;
  END IF;
  SELECT count(*) FILTER (WHERE alias ~ '^[A-Z][a-z]+[A-Z][a-z]+$'), count(DISTINCT lower(alias))
    INTO v_camel, v_distinct
    FROM public.profiles WHERE coalesce(is_horse, false);
  IF v_distinct < 1000 THEN
    RAISE EXCEPTION 'the fleet still shares names: % distinct of 1000', v_distinct;
  END IF;
  IF v_camel > 300 THEN
    RAISE EXCEPTION 'the fleet is still one silhouette: % CapitalCapital', v_camel;
  END IF;
  RAISE NOTICE 'renamed % horses; % distinct; % CapitalCapital', v_updated, v_distinct, v_camel;
END $$;

