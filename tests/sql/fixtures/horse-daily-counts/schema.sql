-- No player data, remote connection, or money/seat authorities in this fixture.
CREATE TABLE public.ca_hand_fact_projection_receipts (
  hand_id uuid NOT NULL,
  source_hash text NOT NULL,
  fact_count integer NOT NULL,
  transfer_count integer NOT NULL,
  projected_at timestamp with time zone DEFAULT clock_timestamp() NOT NULL,
  CHECK (((fact_count >= 1) AND (fact_count <= 10))),
  PRIMARY KEY (hand_id),
  CHECK ((source_hash ~ '^[0-9a-f]{64}$'::text)),
  CHECK (((transfer_count >= 0) AND (transfer_count <= 90)))
);

